// npm run dev:mock
//
// Starts the mock TaxonWorks API and the TaxonPages dev server together.
// While it runs, config/api.development.yml points the dev server at the mock;
// TaxonPages reads *.development.yml files only in dev, never in production
// builds, and the file is removed again on exit.

import { spawn } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync, rmSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { startMockApi } from './server.mjs'

const PORT = Number(process.env.MOCK_API_PORT || 4010)
const MARKER = '# Generated by mock-api/dev.mjs'
const devConfig = fileURLToPath(new URL('../config/api.development.yml', import.meta.url))

const isMockConfig = () => existsSync(devConfig) && readFileSync(devConfig, 'utf8').startsWith(MARKER)

// `--clean` runs as the predev script so a plain `npm run dev` never picks up
// a mock config left behind by a force-killed `npm run dev:mock`.
if (process.argv.includes('--clean')) {
  if (isMockConfig()) {
    rmSync(devConfig)
    console.log('[mock-api] removed leftover config/api.development.yml')
  }
  process.exit(0)
}

if (existsSync(devConfig) && !isMockConfig()) {
  console.error('config/api.development.yml exists and was not created by the mock. Remove it first.')
  process.exit(1)
}

// Start the mock before touching the config: if another preview already holds
// the port, its config file must be left alone.
try {
  await startMockApi(PORT)
} catch (e) {
  console.error(
    e.code === 'EADDRINUSE'
      ? `[mock-api] Port ${PORT} is already in use. Another preview is probably still running: close its terminal, then try again.`
      : `[mock-api] ${e.message}`
  )
  process.exit(1)
}
console.log(`[mock-api] example TaxonWorks API on http://localhost:${PORT}/api/v1 (EXAMPLE DATA)`)

writeFileSync(
  devConfig,
  `${MARKER}; removed on exit. Points npm run dev at example data.\nurl: http://localhost:${PORT}/api/v1\nproject_token: example\n`
)

let cleaned = false
function cleanup() {
  if (cleaned) return
  cleaned = true
  rmSync(devConfig, { force: true })
}

const dev = spawn('npx taxonpages dev', { stdio: 'inherit', shell: true })

dev.on('exit', (code) => {
  cleanup()
  process.exit(code ?? 0)
})

for (const signal of ['SIGINT', 'SIGTERM', 'SIGHUP']) {
  process.on(signal, () => {
    cleanup()
    dev.kill()
    process.exit(0)
  })
}
process.on('exit', cleanup)
